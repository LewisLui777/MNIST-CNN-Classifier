def plotter(batch_numbers,accuracies,title,x_label,y_label):
  plt.plot(batch_numbers,accuracies)
  plt.title(title)
  plt.xlabel(x_label)
  plt.ylabel(y_label)
  plt.grid(True, linestyle=':', alpha=0.6)
  plt.show()
def train_model(model,train_loader,num_epochs,learning_rate,device):
  model.train()
  criterion = nn.CrossEntropyLoss()
  optimizer = torch.optim.Adam(model.parameters(),lr=learning_rate)
  batch_numbers = []
  accuracies = []
  title = 'Accuracy vs Batch Number'
  x_label = 'Batch Number'
  y_label = 'Accuracy'
  epoch_number = 0
  for i in range(num_epochs):
    for j, item in enumerate(train_loader):
      images,labels = item
      images = images.to(device)
      labels = labels.to(device)

      outputs = model(images)
      loss = criterion(outputs,labels)

      optimizer.zero_grad()
      loss.backward()
      optimizer.step()

      if epoch_number % 100 == 0:
        guesses = torch.max(outputs,dim=1)
        accuracies.append((guesses[1] == labels).sum().item() / len(labels) * 100)
        batch_numbers.append(epoch_number)
      epoch_number += 1
  plotter(batch_numbers,accuracies,title,x_label,y_label)

