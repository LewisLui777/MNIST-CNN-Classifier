import torch
import torch.nn as nn
import torchvision
import torchvision.transforms as transforms
import matplotlib.pyplot as plt

def download_training_dataset(batch_size):
  transform = transforms.Compose([transforms.ToTensor(),transforms.Normalize((0.5,), (0.5,))])
  train_set = torchvision.datasets.MNIST('~/.pytorch/MNIST_data/', download=True, train=True, transform=transform)
  train_loader = torch.utils.data.DataLoader(train_set, batch_size=batch_size, shuffle=True)
  return train_loader
def download_testing_dataset(batch_size):
  transform = transforms.Compose([transforms.ToTensor(),transforms.Normalize((0.5,), (0.5,))])
  test_set = torchvision.datasets.MNIST('~/.pytorch/MNIST_data/', download=True, train=False, transform=transform)
  test_loader = torch.utils.data.DataLoader(test_set, batch_size=batch_size, shuffle=True)
  return test_loader

class CNN1(nn.Module):
  #BASE MODEL FOR COMPARISON
  def __init__(self,num_classes=10):
    super(CNN1,self).__init__()
    self.layer1 = nn.Sequential(
        nn.Conv2d(in_channels=1,out_channels=16,kernel_size=5,stride=1,padding=2),
        nn.ReLU(),
        nn.MaxPool2d(kernel_size=2,stride=2)
    ) #14
    self.layer2 = nn.Sequential(
        nn.Conv2d(in_channels=16,out_channels=32,kernel_size=5,stride=1,padding=2),
        nn.ReLU(),
        nn.MaxPool2d(kernel_size=2,stride=2)
    ) #7
    self.layer3 = nn.Sequential(
        nn.Conv2d(in_channels=32,out_channels=64,kernel_size=5,stride=1,padding=2),
        nn.ReLU(),
        nn.MaxPool2d(kernel_size=2,stride=2)
    ) #3
    self.fc1 = nn.Linear(in_features = 3*3*64,out_features=num_classes)

  def forward(self,x):
    x = self.layer1(x)
    x = self.layer2(x)
    x = self.layer3(x)
    x = x.reshape(x.size(0),-1)
    x = self.fc1(x)
    return x
