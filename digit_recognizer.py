def test_model(model,test_loader,device):
  model.eval()
  with torch.no_grad():
    total_samples = 0
    correct_samples = 0
    for i, item in enumerate(test_loader):
      images,labels = item
      images = images.to(device)
      labels = labels.to(device)
      outputs = model(images)
      values, estimates = torch.max(outputs,dim=1)
      total_samples += outputs.size(0)
      correct_samples += (labels == estimates).sum().item()
    return correct_samples * 100 / total_samples

